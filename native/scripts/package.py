#!/usr/bin/env python3
"""Build the root-layout process-extension ZIP plus SHA256 sidecars. No uploads.

Layout: extension.json, bin/tezbar-<slug>[.exe], resources/**, licenses/**,
LICENSE, NOTICE. `files` inventories every member except extension.json.
"""
import argparse, hashlib, json, re, shutil, stat, struct, subprocess, tempfile, zipfile
from pathlib import Path

CRATE = Path(__file__).resolve().parents[1]  # Rust process crate (native/)
REPO = CRATE.parent  # repository root holding the source extension.json
TARGETS = {'aarch64-apple-darwin': False, 'x86_64-pc-windows-msvc': True}
PLATFORM = {False: 'macOS', True: 'Windows'}
SDK = 'tezbar-extension-sdk'
SDK_URL = 'https://github.com/almatkai/tezbar-extension-sdk-rust.git'
SDK_REV = 'aaec571673ab64a85a136cf6bd054ef660c4d93c'
THIRD_PARTY = CRATE / 'licenses' / 'THIRD-PARTY-CRATES.txt'


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def check_binary_target(binary, target):
    data = binary.read_bytes()
    if TARGETS[target]:
        assert data[:2] == b'MZ' and len(data) >= 64, 'Windows package requires a PE executable'
        offset = struct.unpack_from('<I', data, 60)[0]
        assert data[offset:offset + 4] == b'PE\0\0', 'Invalid Windows PE header'
        assert struct.unpack_from('<H', data, offset + 4)[0] == 0x8664, 'Windows package requires x64'
    else:
        assert data[:4] == b'\xcf\xfa\xed\xfe' and len(data) >= 8, 'macOS package requires a 64-bit Mach-O executable'
        assert struct.unpack_from('<I', data, 4)[0] == 0x0100000c, 'macOS package requires arm64'


def check_sdk():
    text = (CRATE / 'Cargo.toml').read_text()
    match = re.search(r'^' + re.escape(SDK) + r'\s*=\s*\{([^}\n]*)\}', text, re.M)
    fields = match.group(1) if match else ''
    revision = re.search(r'\brev\s*=\s*"([0-9a-fA-F]{40})"', fields)
    if not revision or re.search(r'\b(path|branch|tag)\s*=', fields) or not re.search(r'\bgit\s*=\s*"https://github.com/[^" ]+"', fields):
        raise SystemExit('Release blocked: pin the SDK to an approved immutable git revision and regenerate Cargo.lock.')
    if revision.group(1) != SDK_REV or f'git = "{SDK_URL}"' not in fields:
        raise SystemExit('Release blocked: SDK must use the approved repository/revision.')
    lock = (CRATE / 'Cargo.lock').read_text()
    entry = re.search(r'\[\[package\]\]\nname = "' + re.escape(SDK) + r'"(.*?)(?=\[\[package\]\]|\Z)', lock, re.S)
    if not entry or not re.search(r'source = "git\+[^"\n]+#' + revision.group(1) + r'"', entry.group(1)):
        raise SystemExit('Release blocked: Cargo.lock must contain the same immutable SDK git revision.')


def third_party(target):
    """Name/version/license of every non-local crate linked for the target."""
    meta = json.loads(subprocess.check_output(
        ['cargo', 'metadata', '--locked', '--format-version', '1', '--filter-platform', target],
        cwd=CRATE))
    nodes = {n['id']: n for n in meta['resolve']['nodes']}
    packages = {p['id']: p for p in meta['packages']}
    root = meta['resolve']['root']
    seen, stack = set(), [root]
    while stack:  # normal (non-dev, non-build) dependency closure
        node = nodes[stack.pop()]
        for dep in node['deps']:
            if any(k['kind'] is None for k in dep['dep_kinds']) and dep['pkg'] not in seen:
                seen.add(dep['pkg']); stack.append(dep['pkg'])
    rows = sorted({(packages[i]['name'], packages[i]['version'], packages[i].get('license') or 'UNKNOWN', packages[i].get('source') or 'local')
                   for i in seen})
    lines = [f'Rust crates statically linked into the {target} executable (license as declared by each crate).', '']
    lines += [f'{n} {v}\t{l}\t{"path" if s == "local" else s.split("+")[0]}' for n, v, l, s in rows]
    return '\n'.join(lines) + '\n'


def check_third_party(write=False):
    texts = {t: third_party(t) for t in TARGETS}
    header = 'Generated by native/scripts/package.py --write-third-party. Per target:\n\n'
    text = header + '\n'.join(texts[t] for t in sorted(texts))
    if write:
        THIRD_PARTY.write_text(text)
    elif not THIRD_PARTY.exists() or THIRD_PARTY.read_text() != text:
        raise SystemExit('licenses/THIRD-PARTY-CRATES.txt is stale; run package.py --write-third-party')


def build(target, binary, output):
    check_sdk()
    check_binary_target(binary, target)
    check_third_party()
    windows = TARGETS[target]
    manifest = json.loads((REPO / 'extension.json').read_text())
    slug = manifest['slug']
    executable = f'bin/tezbar-{slug}' + ('.exe' if windows else '')
    info = json.loads(subprocess.check_output([str(binary.resolve()), '--protocol-info'], timeout=10))
    assert info['id'] == manifest['id'] and info['version'] == manifest['version'] and info['protocol'] == 1, 'Binary identity mismatch'
    expected = [c['name'] for c in manifest['commands'] if c['runtime'] == 'rust' and PLATFORM[windows] in c['platforms']]
    assert set(info['commands']) == set(expected), 'Binary/manifest platform coverage mismatch'
    assert (CRATE / manifest['icon']).is_file(), 'Manifest icon must be packaged'
    output.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as temp:
        stage = Path(temp)
        (stage / 'bin').mkdir()
        shutil.copy2(binary, stage / executable)
        for name in ['resources', 'licenses']:
            shutil.copytree(CRATE / name, stage / name)
        for name in ['LICENSE', 'NOTICE']:
            shutil.copy2(CRATE / name, stage / name)
        files = {}
        for path in sorted(stage.rglob('*')):
            if path.is_symlink():
                raise ValueError('Symlinks cannot be packaged')
            if path.is_file():
                files[path.relative_to(stage).as_posix()] = digest(path)
        manifest['files'] = files
        # The trusted host catalog pins published archive URL/digests separately.
        manifest['artifacts'] = {}
        (stage / 'extension.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
        archive = output / f'{slug}-{target}.zip'
        with zipfile.ZipFile(archive, 'w', zipfile.ZIP_DEFLATED) as z:
            for path in sorted(stage.rglob('*')):
                if path.is_file():
                    name = path.relative_to(stage).as_posix()
                    entry = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
                    entry.create_system = 3
                    mode = 0o755 if name == executable else 0o644
                    entry.external_attr = (stat.S_IFREG | mode) << 16
                    entry.compress_type = zipfile.ZIP_DEFLATED
                    z.writestr(entry, path.read_bytes())
        with zipfile.ZipFile(archive) as z:
            packaged = json.loads(z.read('extension.json'))
            assert set(z.namelist()) == set(files) | {'extension.json'}
            for name, sha in packaged['files'].items():
                assert hashlib.sha256(z.read(name)).hexdigest() == sha
        artifact = {'target': target, 'sha256': digest(archive), 'executable': executable, 'executableSha256': files[executable]}
        (output / f'{slug}-{target}.artifact.json').write_text(json.dumps(artifact, indent=2) + '\n')
        (output / f'{archive.name}.sha256').write_text(f"{artifact['sha256']}  {archive.name}\n")
        (output / f'{slug}-{target}.{Path(executable).name}.sha256').write_text(f"{artifact['executableSha256']}  {executable}\n")
        (output / f'{slug}-{target}.files.json').write_text(json.dumps(files, indent=2) + '\n')
        print(archive)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--target', choices=TARGETS)
    parser.add_argument('--binary', type=Path)
    parser.add_argument('--output', type=Path, default=CRATE / 'dist')
    parser.add_argument('--write-third-party', action='store_true', help='Regenerate licenses/THIRD-PARTY-CRATES.txt and exit')
    args = parser.parse_args()
    if args.write_third_party:
        check_third_party(write=True)
    else:
        if not args.target or not args.binary:
            parser.error('--target and --binary are required')
        build(args.target, args.binary, args.output)
